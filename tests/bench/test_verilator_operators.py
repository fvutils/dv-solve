"""Benchmark: Verilator-style operator mix.

Models a constraint problem with arithmetic, comparison, and bitwise
operations representative of the patterns generated by Verilator's
constraint compilation.

a, b   -- 8-bit operands
sum_ab -- a + b
diff   -- a - b (signed result)
masked -- a & 0x0F

Constraints:
  sum_ab == a + b
  a < b
  a >= 10
  masked == a & 0x0F
  masked <= 5
"""
import pytest
import zuspec.dataclasses as zdc
from solvers import solvers


@zdc.dataclass
class VerilatorOps:
    a:      zdc.rand(domain=(10, 200),  default=10)
    b:      zdc.rand(domain=(10, 200),  default=20)
    sum_ab: zdc.rand(domain=(20, 400),  default=30)
    masked: zdc.rand(domain=(0, 15),    default=0)

    @zdc.constraint
    def c_sum(self):
        assert self.sum_ab == self.a + self.b

    @zdc.constraint
    def c_order(self):
        assert self.a < self.b

    @zdc.constraint
    def c_masked(self):
        assert self.masked == self.a & 0x0F

    @zdc.constraint
    def c_masked_bound(self):
        assert self.masked <= 5


def _check(sol):
    assert sol["sum_ab"] == sol["a"] + sol["b"]
    assert sol["a"] < sol["b"]
    assert sol["a"] >= 10
    assert sol["masked"] == sol["a"] & 0x0F
    assert sol["masked"] <= 5


@pytest.mark.bench
@pytest.mark.parametrize("solver", solvers(), ids=str)
def test_verilator_operators(solver, tmp_path):
    solver.bench(VerilatorOps, validate=_check, tmp_path=tmp_path)
